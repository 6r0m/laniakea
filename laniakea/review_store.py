"""On-demand disposable reports and separately coordinated durable review decisions."""

import copy
import json
import threading
from pathlib import Path
from time import perf_counter

from . import profiles, review, review_policy
from .workspace import read_json, write_json, writer_lock

CODE_DIGEST=review.digest([Path(p).read_text(encoding='utf-8')
                           for p in (__file__,review.__file__,review_policy.__file__)])

class Conflict(ValueError):
    pass


def bounded_json(path, maximum):
    with Path(path).open('rb') as stream:
        data=stream.read(maximum+1)
    if len(data)>maximum:
        raise ValueError('review file exceeds size limit')
    return json.loads(data)


class Triage:
    def __init__(self, root):
        self.path=Path(root)/'triage.json'
        self.lock=threading.Lock()

    def read(self):
        try:
            value=bounded_json(self.path, 16*1024*1024)
        except FileNotFoundError:
            return {'version':1, 'revision':0, 'decisions':{}}
        review_policy.fields(value, {'version','revision','decisions'})
        if type(value.get('version')) is not int or value['version']!=1 or type(value.get('revision')) is not int or value['revision']<0 or \
                not isinstance(value.get('decisions'),dict):
            raise ValueError('invalid review triage store')
        for key, decision in value['decisions'].items():
            review_policy.fields(decision, {'fingerprint','state','reason'})
            if not isinstance(key,str) or len(key)!=64 or not isinstance(decision.get('fingerprint'),str) or \
                    len(decision['fingerprint'])!=64 or not isinstance(decision.get('state'),str) or \
                    decision['state'] not in {'accepted','not-relevant'}:
                raise ValueError('invalid stored review decision')
            self.reason(decision.get('reason'))
        return value

    @staticmethod
    def reason(reason):
        if not isinstance(reason,str) or len(reason)>2000 or any(ord(c)<32 and c not in '\n\t' for c in reason):
            raise ValueError('invalid review decision reason')

    def update(self, request, finding):
        state=request.get('state'); reason=request.get('reason','')
        self.reason(reason)
        if not isinstance(state,str) or state not in {'accepted','not-relevant','active'} or type(request.get('revision')) is not int:
            raise ValueError('invalid review decision state or revision')
        with self.lock, writer_lock(self.path.with_suffix('.lock'), 'Review decisions are being updated; retry.'):
            data=self.read()
            if request['revision']!=data['revision']:
                raise Conflict('Review revision changed; reload before saving.')
            if state=='active':
                data['decisions'].pop(finding['id'], None)
            else:
                data['decisions'][finding['id']]={'fingerprint':finding['fingerprint'], 'state':state, 'reason':reason}
            data['revision']+=1
            if len(json.dumps(data).encode())>16*1024*1024:
                raise ValueError('review decision store limit reached')
            write_json(self.path, data)


class Review:
    def __init__(self, workspace, target, run, index):
        self.root=workspace.target_dir(target)/'review'
        self.run=Path(run); self.index=index
        self.rules_path=self.root/'rules.json'; self.triage=Triage(self.root)
        self.current=None; self.policy=None; self.lock=threading.RLock(); self.cache_path=None
        self.parents=None

    def rules(self):
        try:
            policy=bounded_json(self.rules_path, 65536)
        except FileNotFoundError:
            policy=copy.deepcopy(review_policy.DEFAULT)
        return review_policy.validate(policy)

    def load(self):
        with self.lock:
            if self.current is not None:
                return self.current
            start=perf_counter(); policy=self.rules()
            if self.parents is None:
                self.parents={n['id']:n['parent'] for n in self.index.topology()['nodes']}
            manifest=read_json(self.run/'manifest.json')
            profile=profiles.PROFILES.get(manifest.get('profile'))
            adapter=getattr(profile, 'review_adapter', None)
            marker=read_json(self.index.root/'cache.json')
            key=review.digest([marker,manifest,policy,CODE_DIGEST,getattr(adapter,'CODE_DIGEST',None)])
            self.cache_path=self.root/'cache'/(key+'.json')
            with writer_lock(self.root/'report.lock', 'Review is being generated by another server; retry.'):
                try:
                    cached=bounded_json(self.cache_path, 32*1024*1024)
                    report=cached['report']
                    if cached['key']!=key or cached['checksum']!=review.digest(report):
                        raise ValueError('review cache checksum mismatch')
                except (FileNotFoundError, ValueError, KeyError, TypeError):
                    report=review.evaluate(self.index.topology()['nodes'],self.index.iter_references(),manifest,policy,adapter)
                    report.update(report=key, policy=policy, elapsed_seconds=perf_counter()-start)
                    encoded={'key':key,'checksum':review.digest(report),'report':report}
                    if len(json.dumps(encoded).encode())>32*1024*1024:
                        raise ValueError('review report limit reached; narrow the policy scope')
                    write_json(self.cache_path, encoded)
            self.policy=policy; self.current=report
            return report

    def page(self, query):
        review_policy.fields(query, {'cursor','limit','ack','report','node','finding'})
        cursor=query.get('cursor',0); limit=query.get('limit',50); ack=query.get('ack',False)
        if type(cursor) is not int or cursor<0 or type(limit) is not int or not 1<=limit<=100 or type(ack) is not bool:
            raise ValueError('invalid review page')
        report=self.load()
        if query.get('report',report['report'])!=report['report']:
            raise Conflict('Review report changed; reload.')
        if 'finding' in query and (not isinstance(query['finding'],str) or
                not any(f['id']==query['finding'] for f in report['findings'])):
            raise ValueError('unknown review finding')
        triage=self.triage.read(); findings=[]; affected={}; connections=[]; counts={'violation':0,'candidate':0,'acknowledged':0}
        decorations=cursor==0 and 'node' not in query and 'finding' not in query
        if 'node' in query and (not isinstance(query['node'],str) or query['node'] not in self.parents):
            raise ValueError('unknown review node')
        def includes(subject):
            while subject is not None:
                if subject==query['node']:
                    return True
                subject=self.parents.get(subject)
            return False
        for finding in report['findings']:
            decision=triage['decisions'].get(finding['id'])
            matching=decision and decision['fingerprint']==finding['fingerprint']
            state=decision['state'] if matching else 'active'
            counts['acknowledged' if matching else finding['severity']]+=1
            if not matching or ack:
                if decorations:
                    connections.append({**{key:finding[key] for key in ('id','kind','title','subjects','severity','groups')},
                                        'acknowledged':bool(matching)})
                for subject in finding['subjects']:
                    affected.setdefault(subject,[]).append({'id':finding['id'],'severity':finding['severity'],
                                                            'acknowledged':bool(matching)})
                if ('node' not in query or any(includes(s) for s in finding['subjects'])) and \
                        ('finding' not in query or query['finding']==finding['id']):
                    findings.append({**finding,'triage':state,'reason_saved':decision['reason'] if matching else '',
                                     'reopened':'Semantic evidence or rule changed.' if decision and not matching else ''})
        return {'report':report['report'], 'revision':triage['revision'], 'counts':counts,
                'affected':affected if decorations else {}, 'connections':connections,
                'checks':report['checks'], 'context':report['context'], 'policy':report['policy'],
                'policy_path':str(self.rules_path), 'elapsed_seconds':report['elapsed_seconds'],
                'items':findings[cursor:cursor+limit], 'total':len(findings),
                'next_cursor':cursor+limit if cursor+limit<len(findings) else None}

    def update(self, request):
        review_policy.fields(request, {'action','report','revision','finding','state','reason'})
        if request.get('action')=='recheck':
            if set(request)!={'action'}:
                raise ValueError('invalid recheck request')
            with self.lock:
                self.current=None; self.policy=None
            return self.page({})
        if request.get('action')!='triage':
            raise ValueError('unknown review action')
        with self.lock:
            report=self.load()
            if request.get('report')!=report['report'] or self.rules()!=self.policy:
                raise Conflict('Review report or policy changed; recheck before saving.')
            finding=next((f for f in report['findings'] if f['id']==request.get('finding')),None)
            if finding is None:
                raise ValueError('unknown review finding')
            self.triage.update(request,finding)
        return {'saved':True}
